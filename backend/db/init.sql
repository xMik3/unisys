DROP DATABASE IF EXISTS universityBranch;
CREATE DATABASE universityBranch CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE universityBranch;

CREATE TABLE Students(
    SID INT NOT NULL AUTO_INCREMENT,
    NAME VARCHAR(30) NOT NULL,
    SURNAME VARCHAR(30) NOT NULL,
    SEMESTER INT NOT NULL,
    PASSWORD VARCHAR(60) NOT NULL,
    ENROLLMENTYEAR INT NOT NULL,
    PRIMARY KEY(SID)
);

CREATE TABLE Teachers(
    TID INT NOT NULL AUTO_INCREMENT,
    NAME VARCHAR(30) NOT NULL,
    SURNAME VARCHAR(30) NOT NULL,
    PASSWORD VARCHAR(60) NOT NULL,
    PRIMARY KEY(TID)
);

CREATE TABLE Courses(
    CID INT NOT NULL AUTO_INCREMENT,
    NAME VARCHAR(60) NOT NULL,
    SEMESTER INT,
    TID INT,
    PRIMARY KEY(CID),
    FOREIGN KEY(TID) REFERENCES Teachers(TID) ON DELETE SET NULL
);

CREATE TABLE Attends(
    SID INT NOT NULL,
    CID INT NOT NULL,
    GRADE DECIMAL(3,1),
    PRIMARY KEY(SID,CID),
    FOREIGN KEY(SID) REFERENCES Students(SID) ON DELETE CASCADE,
    FOREIGN KEY(CID) REFERENCES Courses(CID) ON DELETE CASCADE
);

CREATE INDEX idx_attends_cid ON Attends(CID);
CREATE INDEX idx_courses_tid ON Courses(TID);

